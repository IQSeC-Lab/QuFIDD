#!/usr/bin/env python3
"""inspection_groups.py -- run from Experiments2 (via run_inspection_groups.slurm).
Fig. 3: precision and recall as an analyst inspects the ranked list, for the same six models as the FPR-budget figure
(both quantum versions; best twin and best CADE-mini of each loss setting per dataset, by ROC-AUC in Table I).
Per task (run, split): sort test samples by raw_score (high = drifting); at inspection effort e (k = round(e*P)
inspected samples, P = drifting samples) precision = TP/k, recall = TP/P. Curves are averaged over the 24 tasks.
The mean stopping point of the ranked F1 (mean of per-task k*/P) is marked on each curve and checked against Table I.
Outputs: INSPECTION_GROUPS.csv, fig_inspection_tikz.tex (pgfplots, same style as fig_fpr_budget_tikz.tex)."""
import os, glob, csv
import numpy as np

GRID = np.round(np.arange(0.05, 2.0001, 0.05), 2)
DATASETS = [('EMBER', 'EMBER'), ('Drebin', 'Drebin'), ('lamda', 'LAMDA')]
Q_PAIR = 'ablation_objective/quantum_hybrid_v7_p702_paironly'
Q_FULL = 'quantum_pca8/pennylane/quantum_hybrid_v7_p702'
TW = {c: f'twin_pca8_p702/classical_fidtwin_{c}_702' for c in 'cpr'}
TWP = {c: f'ablation_objective/classical_fidtwin_{c}_702_paironly' for c in 'cpr'}
CP = {'full': 'cade_pca8_p702_proto/cade_full_8_702_proto/tau_10', 'enc': 'cade_pca8_p702_proto/cade_enc_8_702_proto/tau_1',
      'tuned': 'cade_pca8_p702_proto/cade_tuned_8_702_proto/tau_10', 'deep': 'cade_pca8_p702_proto/cade_deep_8_702_proto/tau_1'}
C = {v: f'cade_pca8_p702/cade_{v}_8_702' for v in ('full', 'enc', 'tuned', 'deep')}
# (legend, colour, style, mark, {dataset: folder}, Table I effort for the check or None)
GROUPS = [
    ('Quantum (pair + prototype)', 'qcol', 'line width=1.4pt', '*', {d: Q_FULL for d, _ in DATASETS}, None),
    ('Quantum (pair)', 'qcol', 'line width=1.4pt, densely dashed', 'o', {d: Q_PAIR for d, _ in DATASETS}, None),
    ('Twin (pair + prototype)', 'tcol', 'line width=0.9pt', 'triangle*', {'EMBER': TW['c'], 'Drebin': TW['c'], 'lamda': TW['p']}, None),
    ('Twin (pair)', 'tcol', 'line width=0.9pt, densely dashed', 'triangle', {'EMBER': TWP['r'], 'Drebin': TWP['c'], 'lamda': TWP['c']},
     {'EMBER': 1.41, 'Drebin': 1.22, 'lamda': 1.65}),
    ('CADE-mini (pair + prototype)', 'ccol', 'line width=0.9pt', 'square*', {'EMBER': CP['enc'], 'Drebin': CP['tuned'], 'lamda': CP['deep']},
     {'EMBER': 1.52, 'Drebin': 1.23, 'lamda': 1.70}),
    ('CADE-mini (pair)', 'ccol', 'line width=0.9pt, densely dashed', 'square', {'EMBER': C['enc'], 'Drebin': C['enc'], 'lamda': C['full']},
     {'EMBER': 1.71, 'Drebin': 1.40, 'lamda': 1.71}),
]


def task_curves(f):
    rows = list(csv.DictReader(open(f)))
    s = np.array([float(r['raw_score']) for r in rows]); y = np.array([int(float(r['is_ood'])) for r in rows])
    y = y[np.argsort(-s, kind='stable')]
    P = int(y.sum()); n = len(y)
    tp = np.cumsum(y); k = np.arange(1, n + 1)
    f1 = 2 * tp / (k + P); b = int(np.argmax(f1))
    kk = np.clip(np.round(GRID * P).astype(int), 1, n)
    return tp[kk - 1] / kk, tp[kk - 1] / P, k[b] / P


res = {}
for ds, _ in DATASETS:
    print(f'=== {ds}')
    for leg, *_rest, folders, chk in GROUPS:
        files = sorted(glob.glob(os.path.join(ds, 'pca8', folders[ds], 'results', 'run*', 'split*', 'ood_scores.csv')))
        if not files:
            raise SystemExit(f'no ood_scores.csv for {leg} in {ds}/pca8/{folders[ds]}')
        T = [task_curves(f) for f in files]
        prec = np.mean([t[0] for t in T], 0) * 100; rec = np.mean([t[1] for t in T], 0) * 100
        stop = float(np.mean([t[2] for t in T]))
        res[(ds, leg)] = (prec, rec, stop)
        c = f'   Table I effort {chk[ds]:.2f}' if chk else ''
        print(f'  {leg:30s} n={len(files):2d}  {folders[ds]:55s} stop effort {stop:.2f}{c}'
              f'   prec@1.0 {np.interp(1.0, GRID, prec):5.1f}  rec@1.0 {np.interp(1.0, GRID, rec):5.1f}')

with open('INSPECTION_GROUPS.csv', 'w', newline='') as fh:
    w = csv.writer(fh); w.writerow(['dataset', 'model', 'folder', 'effort', 'precision_pct', 'recall_pct', 'mean_stop_effort'])
    for ds, _ in DATASETS:
        for leg, *_r, folders, _c in GROUPS:
            p, r, s = res[(ds, leg)]
            for e, a, b in zip(GRID, p, r):
                w.writerow([ds, leg, folders[ds], f'{e:.2f}', f'{a:.2f}', f'{b:.2f}', f'{s:.3f}'])

L = [r"""% Precision and recall versus inspection effort (Fig. 3): both quantum versions and the best twin and CADE-mini of each
% loss setting per dataset. Generated by inspection_groups.py from the per-task ood_scores.csv files.
% Preamble: \usepackage{pgfplots}\pgfplotsset{compat=1.18}\usepgfplotslibrary{groupplots}
\definecolor{qcol}{HTML}{2A78D6}  % quantum
\definecolor{tcol}{HTML}{EB6834}  % quantum-inspired twins
\definecolor{ccol}{HTML}{1BAF7A}  % CADE-minis
\begin{figure*}[t]
  \centering
  \begin{tikzpicture}
    \begin{groupplot}[
        group style={group size=3 by 2, horizontal sep=0.6cm, vertical sep=0.45cm,
                     y descriptions at=edge left, x descriptions at=edge bottom},
        width=0.37\textwidth, height=0.22\textwidth,
        xmin=0, xmax=2.05, ymin=0, ymax=100, xtick={0,0.5,1,1.5,2}, ytick={0,25,50,75,100},
        xlabel={Inspection effort (inspected / drifting)},
        tick label style={font=\scriptsize}, label style={font=\scriptsize}, title style={font=\small},
        ymajorgrids, grid style={gray!20}, axis line style={gray!70},
        axis x line*=bottom, axis y line*=left, clip=false,
        every axis plot/.append style={mark size=1.4pt, mark repeat=5, mark phase=4, mark options={solid}},
        legend style={font=\scriptsize, draw=none, legend columns=3, cells={anchor=west}, /tikz/every even column/.append style={column sep=8pt}},
      ]"""]
first = True
for row, (yl, idx) in enumerate([('Precision (\\%)', 0), ('Recall (\\%)', 1)]):
    for j, (ds, title) in enumerate(DATASETS):
        opt = [f'title={{{title}}}'] if row == 0 else []
        if j == 0:
            opt.append(f'ylabel={{{yl}}}')
        if first:
            opt.append('legend to name=inspleg')
        L.append(f"      \\nextgroupplot[{', '.join(opt)}]")
        for leg, col, sty, mk, folders, _c in GROUPS:
            curve = res[(ds, leg)][idx]
            pts = ' '.join(f'({e:g},{v:.1f})' for e, v in zip(GRID, curve))
            L.append(f"        \\addplot[{col}, {sty}, mark={mk}{'' if first else ', forget plot'}] coordinates {{{pts}}};")
            if first:
                L.append(f'        \\addlegendentry{{{leg}}}')
        for leg, col, *_r in GROUPS:  # mean stopping point of the ranked F1
            curve, stop = res[(ds, leg)][idx], res[(ds, leg)][2]
            L.append(f'        \\draw[{col}, line width=1.2pt] (axis cs:{stop:.3f},{np.interp(stop, GRID, curve) - 4:.1f}) -- '
                     f'(axis cs:{stop:.3f},{np.interp(stop, GRID, curve) + 4:.1f});')
        first = False
L.append(r"""    \end{groupplot}
  \end{tikzpicture}\\[2pt]
  \pgfplotslegendfromname{inspleg}
  \caption{Precision (top) and recall (bottom) as an analyst inspects the ranked list, averaged over the $24$ tasks of each dataset, for both quantum versions and the best twin and CADE-mini of each loss setting on that dataset, the same models as in Fig.~\ref{fig:fpr_budget}. Solid lines show models trained with the pairwise and the prototype loss, dashed lines models trained with the pairwise loss alone. The x-axis is the inspection effort, the number of inspected samples divided by the number of drifting samples; vertical ticks mark the mean stopping point of the ranked F1.}
  \label{fig:inspection}
\end{figure*}""")
open('fig_inspection_tikz.tex', 'w').write('\n'.join(L) + '\n')
print('\nstop effort = mean over tasks of k*/P at the ranked-F1 stopping point (should match Table I where given)')
print('Saved INSPECTION_GROUPS.csv and fig_inspection_tikz.tex')
