"""Writes figures/fig_reupload_tikz.tex (pgfplots, 2 rows x 3 panels, legend on the right) from DX_reupload.csv."""
import csv
R = list(csv.DictReader(open('DX_reupload.csv')))
DS = [('EMBER','EMBER-2018'), ('Drebin','DREBIN'), ('LAMDA','LAMDA')]
MOD = [('Quantum (pair loss only)', 'solid', r'\QF{pair}'),
       ('Quantum (pair + prototype)', 'densely dashed', r'\QF{pair+proto}')]
def get(ds, mod, grp):
    r = sorted([x for x in R if x['dataset']==ds and x['model']==mod and x['group']==grp], key=lambda x: int(x['after_reupload']))
    return [(int(x['after_reupload']), float(x['mean_distance'])) for x in r]
def coords(p): return ' '.join('(%d,%.4f)' % q for q in p)
out = [r"""% Re-upload decomposition of QuFiDD (2 x 3, legend right). Generated by gen_reupload_tikz.py from DX_reupload.csv.
% Preamble: \usepackage{pgfplots}\pgfplotsset{compat=1.18}\usepgfplotslibrary{groupplots}
\definecolor{qcol}{HTML}{2A78D6}\definecolor{kcol}{HTML}{808080}
\begin{figure*}[t]
  \centering
  \begin{tikzpicture}
    \begin{groupplot}[
        group style={group size=3 by 2, horizontal sep=0.7cm, vertical sep=0.18cm, x descriptions at=edge bottom},
        width=0.255\textwidth, scale only axis, xmin=0, xmax=24, xtick={0,4,8,12,16,20,24},
        tick label style={font=\scriptsize}, label style={font=\scriptsize},
        ymajorgrids, xmajorgrids, grid style={gray!20}, axis line style={gray!70},
        axis x line*=bottom, axis y line*=left, major tick length=2pt,
        yticklabel style={/pgf/number format/.cd, fixed, fixed zerofill, precision=1},
        legend style={font=\scriptsize, draw=none, legend columns=1, at={(1.04,1)}, anchor=north west,
                      cells={anchor=west}, row sep=1pt},
      ]
"""]
for j, (ds, dn) in enumerate(DS):
    opt = 'height=2.7cm' + (', ylabel={Mean distance to prototype}' if j == 0 else '')
    out.append('      \\nextgroupplot[%s]\n' % opt)
    out.append('        \\node[font=\\scriptsize\\bfseries, anchor=north east, inner sep=2pt] at (rel axis cs:1,1) {%s};\n' % dn)
    for mod, ls, lab in MOD:
        out.append('        \\addplot[kcol, line width=1.1pt, %s] coordinates {%s};\n' % (ls, coords(get(ds, mod, 'known'))))
        if j == 2: out.append('        \\addlegendentry{known, %s}\n' % lab)
        out.append('        \\addplot[qcol, line width=1.1pt, %s] coordinates {%s};\n' % (ls, coords(get(ds, mod, 'drifting'))))
        if j == 2: out.append('        \\addlegendentry{drifting, %s}\n' % lab)
    if j == 2:
        out.append('        \\addlegendimage{black, line width=1.0pt}\\addlegendentry{drifting / known (bottom)}\n')
for j, (ds, dn) in enumerate(DS):
    opt = 'height=1.9cm' + (', ylabel={Drifting / known}' if j == 0 else '') + (', xlabel={Re-upload layer (0 = after encoding)}' if j == 1 else '')
    out.append('      \\nextgroupplot[%s]\n' % opt)
    for mod, ls, lab in MOD:
        k = dict(get(ds, mod, 'known')); d = get(ds, mod, 'drifting')
        out.append('        \\addplot[black, line width=1.0pt, %s] coordinates {%s};\n' % (ls, coords([(u, v / k[u]) for u, v in d])))
out.append(r"""    \end{groupplot}
  \end{tikzpicture}
  \caption{Re-upload decomposition of QuFiDD. Top: mean fidelity distance of known and drifting test samples to their closest prototype after the amplitude encoding (layer 0) and after each of the 24 re-uploads. Bottom: ratio of the drifting to the known distance.}
  \label{fig:reupload}
\end{figure*}
""")
open('figures/fig_reupload_tikz.tex', 'w').write(''.join(out))
print('wrote figures/fig_reupload_tikz.tex')
